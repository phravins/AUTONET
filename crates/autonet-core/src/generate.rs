//! Render the current address as a file a project can read.
//!
//! `autonet dev` keeps one of these files current for each output a project
//! needs, so source code can name `AutoNet.url` and never an address. This module
//! is the pure half: given the values, produce the text. Writing it, and deciding
//! when to, belongs to the CLI.
//!
//! Every format carries [`MARKER`]. That is what lets the writer tell its own
//! file from one a person wrote at the same path, and what lets `autonet check`
//! skip a file whose whole job is to contain an address.

use std::fmt::Write as _;

use serde::{Deserialize, Serialize};

/// The text that identifies a file as AutoNet's to overwrite.
pub const MARKER: &str = "Generated by autonet";

/// The sentence at the top of every generated file.
const HEADER: &str = "Generated by autonet. Do not edit or commit: `autonet dev` rewrites this file when the network changes.";

/// The shape of a generated file.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Format {
    /// `KEY=value` lines, for anything that reads a dotenv file.
    Env,
    /// A TypeScript module exporting `AutoNet`.
    Ts,
    /// A JavaScript module exporting `AutoNet`.
    Js,
    /// A JSON document.
    Json,
    /// A Dart library declaring `class AutoNet`.
    Dart,
    /// Java properties, for Gradle to load.
    Properties,
    /// An Xcode build configuration file.
    Xcconfig,
}

/// One file `autonet dev` keeps current.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct OutputSpec {
    /// The shape of the file.
    pub format: Format,
    /// Where it goes, relative to the project root.
    pub path: String,
    /// Prepended to each variable of an `env` file, such as `VITE_`.
    ///
    /// Frameworks only expose variables with their own prefix to client code,
    /// so without this the file would be written and the app could not see it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub prefix: Option<String>,
}

/// What a generated file says.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Values {
    /// The address, bare.
    pub ip: String,
    /// The address ready for a URL, with IPv6 bracketed.
    pub host: String,
    /// The URL to open, when a port is known.
    pub url: Option<String>,
    /// The port, when one is known.
    pub port: Option<u16>,
    /// False when nothing is selectable and these values are the last known.
    pub online: bool,
}

/// Whether `contents` came from [`render`], and so may be overwritten.
pub fn is_generated(contents: &str) -> bool {
    contents.contains(MARKER)
}

/// Render `values` in the shape `spec` asks for.
pub fn render(spec: &OutputSpec, values: &Values) -> String {
    match spec.format {
        Format::Env => env(spec.prefix.as_deref().unwrap_or(""), values),
        Format::Ts => module(values, " as const"),
        Format::Js => module(values, ""),
        Format::Json => json(values),
        Format::Dart => dart(values),
        Format::Properties => properties(values),
        Format::Xcconfig => xcconfig(values),
    }
}

fn env(prefix: &str, values: &Values) -> String {
    let mut text = format!("# {HEADER}\n");
    let mut line = |name: &str, value: &str| {
        let _ = writeln!(text, "{prefix}AUTONET_{name}={value}");
    };
    line("IP", &values.ip);
    line("HOST", &values.host);
    // Absent rather than empty. A framework cannot tell an empty string from a
    // value, so `fetch(import.meta.env.VITE_AUTONET_URL + path)` would quietly
    // request a relative path instead of failing.
    if let Some(url) = &values.url {
        line("URL", url);
    }
    if let Some(port) = values.port {
        line("PORT", &port.to_string());
    }
    line("ONLINE", if values.online { "true" } else { "false" });
    text
}

fn module(values: &Values, suffix: &str) -> String {
    format!(
        "// {HEADER}\nexport const AutoNet = {{\n  ip: {},\n  host: {},\n  url: {},\n  port: {},\n  online: {},\n}}{suffix};\n",
        quoted(&values.ip),
        quoted(&values.host),
        optional(values.url.as_deref()),
        port(values.port),
        values.online,
    )
}

fn json(values: &Values) -> String {
    format!(
        "{{\n  \"_comment\": {},\n  \"ip\": {},\n  \"host\": {},\n  \"url\": {},\n  \"port\": {},\n  \"online\": {}\n}}\n",
        quoted(HEADER),
        quoted(&values.ip),
        quoted(&values.host),
        optional(values.url.as_deref()),
        port(values.port),
        values.online,
    )
}

fn dart(values: &Values) -> String {
    let url = values
        .url
        .as_deref()
        .map_or_else(|| "null".to_string(), dart_string);
    format!(
        "// {HEADER}\nclass AutoNet {{\n  AutoNet._();\n\n  static const String ip = {};\n  static const String host = {};\n  static const String? url = {url};\n  static const int? port = {};\n  static const bool online = {};\n}}\n",
        dart_string(&values.ip),
        dart_string(&values.host),
        port(values.port),
        values.online,
    )
}

fn properties(values: &Values) -> String {
    let mut text = format!("# {HEADER}\n");
    let _ = writeln!(text, "autonet.ip={}", values.ip);
    let _ = writeln!(text, "autonet.host={}", values.host);
    if let Some(url) = &values.url {
        let _ = writeln!(text, "autonet.url={url}");
    }
    if let Some(port) = values.port {
        let _ = writeln!(text, "autonet.port={port}");
    }
    let _ = writeln!(text, "autonet.online={}", values.online);
    text
}

fn xcconfig(values: &Values) -> String {
    let mut text = format!("// {HEADER}\n");
    let _ = writeln!(text, "AUTONET_IP = {}", values.ip);
    let _ = writeln!(text, "AUTONET_HOST = {}", values.host);
    if let Some(url) = &values.url {
        // xcconfig treats `//` as a comment even inside a value, so a plain URL
        // is silently cut down to `http:`. An empty `$()` between the slashes is
        // the standard way to keep them apart.
        let _ = writeln!(text, "AUTONET_URL = {}", url.replacen("//", "/$()/", 1));
    }
    if let Some(port) = values.port {
        let _ = writeln!(text, "AUTONET_PORT = {port}");
    }
    let _ = writeln!(
        text,
        "AUTONET_ONLINE = {}",
        if values.online { "YES" } else { "NO" }
    );
    text
}

fn quoted(value: &str) -> String {
    serde_json::Value::from(value).to_string()
}

fn optional(value: Option<&str>) -> String {
    value.map_or_else(|| "null".to_string(), quoted)
}

fn port(port: Option<u16>) -> String {
    port.map_or_else(|| "null".to_string(), |port| port.to_string())
}

fn dart_string(value: &str) -> String {
    format!("'{value}'")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec(format: Format) -> OutputSpec {
        OutputSpec {
            format,
            path: "out".into(),
            prefix: None,
        }
    }

    fn with_port() -> Values {
        Values {
            ip: "192.168.1.20".into(),
            host: "192.168.1.20".into(),
            url: Some("http://192.168.1.20:3000".into()),
            port: Some(3000),
            online: true,
        }
    }

    fn without_port() -> Values {
        Values {
            url: None,
            port: None,
            ..with_port()
        }
    }

    const ALL: [Format; 7] = [
        Format::Env,
        Format::Ts,
        Format::Js,
        Format::Json,
        Format::Dart,
        Format::Properties,
        Format::Xcconfig,
    ];

    #[test]
    fn every_format_is_marked_so_it_can_be_recognised_later() {
        for format in ALL {
            assert!(
                is_generated(&render(&spec(format), &with_port())),
                "{format:?}"
            );
        }
    }

    #[test]
    fn a_file_a_person_wrote_is_not_mistaken_for_a_generated_one() {
        assert!(!is_generated("API_KEY=secret\n"));
    }

    #[test]
    fn an_env_file_carries_the_prefix_its_framework_exposes_to_client_code() {
        let spec = OutputSpec {
            prefix: Some("VITE_".into()),
            ..spec(Format::Env)
        };
        let text = render(&spec, &with_port());
        assert!(text.contains("VITE_AUTONET_URL=http://192.168.1.20:3000\n"));
        assert!(text.contains("VITE_AUTONET_IP=192.168.1.20\n"));
        assert!(text.contains("VITE_AUTONET_ONLINE=true\n"));
    }

    #[test]
    fn an_env_file_omits_the_url_rather_than_leaving_it_empty() {
        let text = render(&spec(Format::Env), &without_port());
        assert!(!text.contains("AUTONET_URL"));
        assert!(!text.contains("AUTONET_PORT"));
        assert!(text.contains("AUTONET_HOST=192.168.1.20\n"));
    }

    #[test]
    fn the_typescript_module_is_narrowed_and_the_javascript_one_is_valid_without_it() {
        let ts = render(&spec(Format::Ts), &with_port());
        assert!(ts.contains("export const AutoNet = {"));
        assert!(ts.contains("url: \"http://192.168.1.20:3000\","));
        assert!(ts.ends_with("} as const;\n"));

        let js = render(&spec(Format::Js), &with_port());
        assert!(js.ends_with("};\n"), "`as const` is a syntax error in JS");
    }

    #[test]
    fn a_module_says_null_when_there_is_no_port() {
        let ts = render(&spec(Format::Ts), &without_port());
        assert!(ts.contains("url: null,"));
        assert!(ts.contains("port: null,"));
    }

    #[test]
    fn the_json_document_parses_and_says_what_it_is() {
        let text = render(&spec(Format::Json), &with_port());
        let parsed: serde_json::Value = serde_json::from_str(&text).unwrap();
        assert_eq!(parsed["url"], "http://192.168.1.20:3000");
        assert_eq!(parsed["port"], 3000);
        assert_eq!(parsed["online"], true);

        let text = render(&spec(Format::Json), &without_port());
        let parsed: serde_json::Value = serde_json::from_str(&text).unwrap();
        assert!(parsed["url"].is_null());
    }

    #[test]
    fn the_dart_class_can_be_read_as_a_compile_time_constant() {
        let text = render(&spec(Format::Dart), &with_port());
        assert!(text.contains("class AutoNet {"));
        assert!(text.contains("static const String? url = 'http://192.168.1.20:3000';"));
        assert!(text.contains("static const int? port = 3000;"));

        let text = render(&spec(Format::Dart), &without_port());
        assert!(text.contains("static const String? url = null;"));
    }

    #[test]
    fn a_properties_file_uses_names_gradle_can_look_up() {
        let text = render(&spec(Format::Properties), &with_port());
        assert!(text.contains("autonet.url=http://192.168.1.20:3000\n"));
        assert!(text.contains("autonet.online=true\n"));
    }

    #[test]
    fn an_xcconfig_url_survives_xcodes_comment_syntax() {
        // A bare `//` would turn the rest of the line into a comment, leaving
        // AUTONET_URL as `http:`. Nothing would report that until the app ran.
        let text = render(&spec(Format::Xcconfig), &with_port());
        assert!(text.contains("AUTONET_URL = http:/$()/192.168.1.20:3000\n"));
        assert!(text.contains("AUTONET_ONLINE = YES\n"));
    }

    #[test]
    fn an_offline_file_says_so_in_every_format() {
        let offline = Values {
            online: false,
            ..with_port()
        };
        for format in ALL {
            let text = render(&spec(format), &offline).to_lowercase();
            assert!(
                text.contains("false") || text.contains("= no"),
                "{format:?} did not report being offline"
            );
        }
    }

    #[test]
    fn an_ipv6_address_stays_bare_in_one_field_and_bracketed_in_the_other() {
        let values = Values {
            ip: "fd00::1".into(),
            host: "[fd00::1]".into(),
            url: Some("http://[fd00::1]:3000".into()),
            port: Some(3000),
            online: true,
        };
        let text = render(&spec(Format::Env), &values);
        assert!(text.contains("AUTONET_IP=fd00::1\n"));
        assert!(text.contains("AUTONET_HOST=[fd00::1]\n"));
    }

    #[test]
    fn the_format_names_in_a_project_file_are_lowercase() {
        let parsed: OutputSpec =
            toml::from_str("format = \"xcconfig\"\npath = \"Autonet.xcconfig\"").unwrap();
        assert_eq!(parsed.format, Format::Xcconfig);
    }

    #[test]
    fn an_unknown_key_on_an_output_is_refused() {
        assert!(
            toml::from_str::<OutputSpec>("format = \"env\"\npath = \"x\"\nprefx = \"A\"").is_err()
        );
    }
}
